  private getInitialLang(): Language {
    if (typeof window !== 'undefined' && window.localStorage) {
      const saved = window.localStorage.getItem(this.STORAGE_KEY) as Language;
      if (saved === 'es' || saved === 'en') {
        return saved;
      }
    }
    return 'es';
  }

  setLang(lang: Language): void {
    this.currentLang.set(lang);
    if (typeof window !== 'undefined' && window.localStorage) {
      window.localStorage.setItem(this.STORAGE_KEY, lang);
    }
  }

  toggleLang(): void {
    this.setLang(this.currentLang() === 'es' ? 'en' : 'es');
  }

  t(key: string): string {
    const lang = this.currentLang();
    return this.translations[lang]?.[key] || this.translations['es']?.[key] || key;
  }
